    private val dbTranslations = java.util.concurrent.ConcurrentHashMap<String, Map<String, String>>()

    fun loadFromDatabase(items: List<LocalizationItem>) {
        dbTranslations.clear()
        items.forEach { item ->
            val langMap = mapOf(
                "en" to item.en,
                "ru" to item.ru,
                "uk" to item.ru,
                "es" to item.es,
                "he" to item.he,
                "de" to item.de,
                "fr" to item.fr,
                "pt" to item.pt,
                "it" to item.it,
                "zh" to item.zh,
                "ja" to item.ja
            )
            dbTranslations[item.key] = langMap
        }
    }

    val languages = listOf(
        "en" to "English",
        "ru" to "Русский",
        "uk" to "Українська",
        "es" to "Español",
        "he" to "עברית (Hebrew)",
        "de" to "Deutsch",
        "fr" to "Français",
        "pt" to "Português",
        "it" to "Italiano",
        "zh" to "中文 (Chinese)",
        "ja" to "日本語 (Japanese)"
    )

    fun getSystemDefaultLanguage(): String {
        val deviceLang = java.util.Locale.getDefault().language
        val supportedLanguages = listOf("en", "ru", "uk", "es", "he", "de", "fr", "pt", "it", "zh", "ja")
        return if (deviceLang in supportedLanguages) deviceLang else "en"
    }

    fun getString(lang: String, key: String): String {
        val activeLang = if (lang.isBlank() || lang == "default") getSystemDefaultLanguage() else lang
        val dbDict = dbTranslations[key]
        if (dbDict != null) {
            return dbDict[activeLang] ?: dbDict["en"] ?: key
        }
        val dict = translations[activeLang] ?: translations["en"]!!
        return dict[key] ?: translations["en"]?.get(key) ?: key
    }
