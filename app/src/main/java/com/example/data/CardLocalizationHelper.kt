    private val dbCardTranslations = java.util.concurrent.ConcurrentHashMap<Int, CardLocalizationItem>()

    fun loadFromDatabase(items: List<CardLocalizationItem>) {
        dbCardTranslations.clear()
        items.forEach { item ->
            dbCardTranslations[item.cardIndex] = item
        }
    }

    fun getLocalizedName(index: Int, lang: String): String {
        val item = dbCardTranslations[index]
        if (item != null) {
            return when (lang) {
                "en" -> item.nameEn
                "ru" -> item.nameRu
                "es" -> item.nameEs
                "he" -> item.nameHe
                "de" -> item.nameDe
                "fr" -> item.nameFr
                "pt" -> item.namePt
                "it" -> item.nameIt
                "zh" -> item.nameZh
                "ja" -> item.nameJa
                else -> item.nameEn
            }
        }
        return cardNames[index]?.get(lang) ?: cardNames[index]?.get("en") ?: ""
    }

